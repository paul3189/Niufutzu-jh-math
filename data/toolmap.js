/* 國中數學｜工具地圖資料骨架
 * 各領域資料由 data/jm-*.js 依序呼叫 TM(...) 註冊。
 *
 * 領域 domain = {
 *   id, n(名稱), icon, color, ask(這個領域回答什麼問題),
 *   geo: true            → 幾何領域，以圖為主（分支頁會用圖卡版面）
 *   topics: [ {
 *      id, n(主題), g(年級 7/8/9), kw:[觸發關鍵字], flow(破題思路一句),
 *      fig(主題代表圖，對應 data/figs.js 的 key),
 *      tools: [ {
 *        n(工具名), d(定義), f(公式／性質 LaTeX), w(什麼時候用), l(限制/前提),
 *        t(常見錯誤), x(延伸), fig(圖), g(年級，未寫則沿用主題)
 *      } ]
 *
 * 幾何圖形的條目一律「先定義、再性質」：
 *   d 寫這個圖形「是什麼」（一句話的定義，抽屜裡排在最上面）
 *   f 寫它「有什麼性質」（用 \begin{gathered} 條列，一條一行）
 * 非圖形的工具（公式、解題法）通常只有 f，不必寫 d。
 *   } ]
 * }
 *
 * 年級 g 的用途：畫面右上角可切「七年級／八年級／九年級」，會依這個欄位過濾。
 * 一個主題若橫跨兩個年級，g 可寫成陣列，例如 g: [7, 8]。
 */
window.TOOLMAP = { domains: [] };
window.TM = function (d) { window.TOOLMAP.domains.push(d); };
