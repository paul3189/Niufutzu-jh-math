  /* ── 三角形全等：判別法分類（八年級）── */
  var TRI2 = [["D", "E", "F"], ["P", "Q", "R"], ["X", "Y", "Z"]];
  function gCongWhich() {
    var P = ["A", "B", "C"], Q = pick(TRI2);
    function side(i, j) {
      if (ri(2)) { var t = i; i = j; j = t; }
      return "$\\overline{" + P[i] + P[j] + "}=\\overline{" + Q[i] + Q[j] + "}$";
    }
    function ang(i, right) {
      return "$\\angle " + P[i] + "=\\angle " + Q[i] + (right ? "=90^\\circ" : "") + "$";
    }
    var v = ri(3), o = [0, 1, 2].filter(function (x) { return x !== v; });
    var a = o[0], b = o[1];
    if (ri(2)) { a = o[1]; b = o[0]; }
    var type = pick(["SSS", "SAS", "SAS", "ASA", "AAS", "AAS", "SSA", "AAA", "RHS", "RHS", "SASR"]);
    var cond, ans;
    if (type === "SSS") { cond = [side(0, 1), side(1, 2), side(0, 2)]; ans = "SSS"; }
    else if (type === "SAS") { cond = [side(v, a), side(v, b), ang(v)]; ans = "SAS"; }
    else if (type === "SASR") { cond = [side(v, a), side(v, b), ang(v, true)]; ans = "SAS"; }
    else if (type === "ASA") { cond = [ang(a), ang(b), side(a, b)]; ans = "ASA"; }
    else if (type === "AAS") { cond = [ang(a), ang(b), side(v, pick([a, b]))]; ans = "AAS"; }
    else if (type === "SSA") { cond = [side(v, a), side(a, b), ang(v)]; ans = "不一定全等"; }
    else if (type === "AAA") { cond = [ang(0), ang(1), ang(2)]; ans = "不一定全等"; }
    else { cond = [ang(v, true), side(a, b), side(v, a)]; ans = "RHS"; }
    var wrongs = {
      "SSS": ["SAS", "RHS", "不一定全等"],
      "SAS": type === "SASR" ? ["RHS", "SSA，不一定全等", "ASA"] : ["ASA", "SSS", "不一定全等"],
      "ASA": ["AAS", "SAS", "不一定全等"],
      "AAS": ["ASA", "SAS", "不一定全等"],
      "RHS": ["SAS", "AAS", "不一定全等"],
      "不一定全等": type === "AAA" ? ["AAA", "ASA", "SSS"] : ["SAS", "RHS", "ASA"]
    }[ans];
    var tips = {
      SSS: "三邊對應相等 → SSS",
      SAS: "兩邊加上它們的<b>夾角</b>（$\\angle " + P[v] + "$ 夾在兩邊之間）→ SAS",
      SASR: "$90^\\circ$ 是兩股的<b>夾角</b>，給的是兩股不是斜邊 → SAS（不是 RHS）",
      ASA: "兩角加上它們<b>中間</b>的邊 → ASA",
      AAS: "兩角加上一組<b>非夾邊</b> → AAS",
      SSA: "給的角不在兩邊之間（SSA）→ 可能有兩種三角形，不一定全等",
      AAA: "三個角相等只能保證形狀一樣（相似），大小不一定 → 不一定全等",
      RHS: "直角對的邊 $\\overline{" + P[a] + P[b] + "}$ 是斜邊，再加一股 → RHS"
    };
    return H.mk("geo", "angle.cong", 8,
      "$\\triangle ABC$ 與 $\\triangle " + Q.join("") + "$ 中，" + shuffle(cond).join("、") + "，可判定全等的依據是？",
      ans, wrongs, tips[type]);
  }

