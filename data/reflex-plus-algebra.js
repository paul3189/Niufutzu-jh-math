  /* 一項：係數 c、文字 v（"" 表示常數項）；first = 是否為第一項 */
  function term(c, v, first) {
    if (c === 0) return "";
    var a = Math.abs(c), k = (a === 1 && v) ? "" : String(a);
    var s = c < 0 ? (first ? "-" : "-") : (first ? "" : "+");
    return s + k + v;
  }
  /* 多項式：cs = [[係數, 文字], ...]，零係數略過 */
  function poly(cs) {
    var out = "", first = true;
    cs.forEach(function (t) {
      if (t[0] === 0) return;
      out += term(t[0], t[1], first); first = false;
    });
    return out || "0";
  }
  /* (x+p) 形式的括號 */
  function lin(p, v) { return "(" + (v || "x") + (p < 0 ? "-" + (-p) : "+" + p) + ")"; }
  function D(s) { return "$" + s + "$"; }

